def _banner(output, sources):
    return (f"/*! {output}: generated by pipeline/bundling.py from "
            f"{len(sources)} sources. Edit those, then run "
            f"`python3 -m pipeline.bundling`. */\n")


def bundle_text(site_dir, output):
    """The bundle's full text, built from the sources under site_dir."""
    sources = BUNDLES[output]
    parts = []
    for name in sources:
        with open(os.path.join(site_dir, name), encoding="utf-8") as f:
            parts.append(f.read())
    if output.endswith(".css"):
        body = rcssmin.cssmin("\n".join(parts), keep_bang_comments=True)
    else:
        # Each source is a complete script on its own; the empty statement
        # between two keeps a file that ends without a semicolon from
        # swallowing the next file's first line. Template literals ride
        # through behind placeholders: rjsmin strips the spaces in one nested
        # inside another's ${...} (pipeline/js_templates.py).
        code, literals = js_templates.protect("\n;\n".join(parts))
        body = js_templates.restore(rjsmin.jsmin(code, keep_bang_comments=True), literals)
    return _banner(output, sources) + body + "\n"


def build_bundles(site_dir=None):
    """Write every bundle whose text changed; return the names written."""
    site_dir = site_dir or config.SITE_DIR
    written = []
    for output in BUNDLES:
        text = bundle_text(site_dir, output)
        path = os.path.join(site_dir, output)
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                current = f.read()
        if current == text:
            continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        written.append(output)
    return written


if __name__ == "__main__":
    from pipeline import stamping

    for _name in build_bundles():
        print(f"  Built {_name}")
